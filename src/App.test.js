test('skills evidence does not cite CPTS or CISM', () => {
  const blob = JSON.stringify(SKILLS_DATA);
  expect(SKILLS_DATA.length).toBeGreaterThan(50);
  expect(blob).not.toMatch(/CPTS/i);
  expect(blob).not.toMatch(/CISM/i);
  expect(SKILLS_DATA.every(skill => skill.sources.length > 0)).toBe(true);
  const bgp = SKILLS_DATA.find(skill => skill.name.startsWith('BGP'));
  expect(bgp.name).toBe('BGP / OSPF');
  expect(JSON.stringify(bgp.sources)).not.toMatch(/EIGRP|Cisco|Juniper/);
  expect(JSON.stringify(bgp.sources)).not.toMatch(/Booz Allen — Tier 2\/3 BGP/);
  const vmware = SKILLS_DATA.find(skill => skill.name.startsWith('VMware'));
  expect(JSON.stringify(vmware.sources)).toMatch(/Booz Allen — VMware ESXi hosts/);
  expect(JSON.stringify(vmware.sources)).toMatch(/Cole Engineering — VMware ESXi hosts/);
  const siem = SKILLS_DATA.find(skill => skill.name.startsWith('SIEM'));
  const ranges = SKILLS_DATA.find(skill => skill.name.startsWith('CTF'));
  expect(JSON.stringify(ranges.sources)).toMatch(/Booz Allen — Cyber Range Engineer/);
  expect(JSON.stringify(siem.sources)).toMatch(/Suricata\/Zeek\/Elastic stack/);
  expect(JSON.stringify(siem.sources)).toMatch(/Booz Allen — Security Onion\/Splunk/);
  expect(JSON.stringify(siem.sources)).toMatch(/Cole Engineering — Security Onion\/Splunk/);
  const iac = SKILLS_DATA.find(skill => skill.name.startsWith('Infrastructure as Code'));
  expect(JSON.stringify(iac.sources)).toMatch(/Booz Allen — Terraform for infrastructure as code/);
  expect(JSON.stringify(iac.sources)).toMatch(/configuration management \(Ansible\/Puppet\)/);
  const vlans = SKILLS_DATA.find(skill => skill.name.startsWith('VLANs'));
  expect(JSON.stringify(vlans.sources)).toMatch(/VLANs, trunking, and inter-VLAN routing/);
  const docker = SKILLS_DATA.find(skill => skill.name.startsWith('Containerization'));
  expect(JSON.stringify(docker.sources)).toMatch(/Docker containers/);
  expect(JSON.stringify(docker.sources)).not.toMatch(/Booz Allen — Kubernetes/);
  const hyper = SKILLS_DATA.find(skill => skill.name.startsWith('Virtualization Platforms'));
  expect(JSON.stringify(hyper.sources)).toMatch(/Proxmox\/Hyper-V/);
  const windows = SKILLS_DATA.find(skill => skill.name === 'Windows Administration');
  expect(JSON.stringify(windows.sources)).toMatch(/Active Directory and DNS/);
  expect(JSON.stringify(iac.sources)).not.toMatch(/module|pipeline|faster/i);
  const python = SKILLS_DATA.find(skill => skill.name === 'Python');
  expect(JSON.stringify(python.sources)).toMatch(/Booz Allen — REST APIs and traffic-generation scripts/);
  const bash = SKILLS_DATA.find(skill => skill.name.startsWith('Bash'));
  expect(JSON.stringify(bash.sources)).toMatch(/Booz Allen — environment builds and traffic-generation scripts/);
  expect(JSON.stringify(SKILLS_DATA)).not.toMatch(/Cisco|Juniper|MikroTik|Palo Alto|EIGRP|\bIOS\b|Scapy|GitLab|shellcode|CCNA|CISSP/);
  const cabling = SKILLS_DATA.find(skill => skill.name.startsWith('Cabling'));
  expect(JSON.stringify(cabling.sources)).toMatch(/Cole Engineering — fiber-optic cabling installation/);
});
